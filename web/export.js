"use strict";
/* Routine export — draws the timetable page(s) on a canvas (A4 portrait, ~200 dpi),
   then either saves them as PNG or wraps them in a real PDF file. No libraries, works offline. */
const Export = (() => {
  const W = 1654, H = 2339, M = 100, TW = W - 2 * M;
  const ACCENT = "#0b5a38";          // table header colour (BAIUST green) — change here to restyle
  const GOLD = "#e8b100";
  const F = "Arial, 'Liberation Sans', Helvetica, sans-serif";
  const COLS = [.15, .40, .15, .13, .17].map(f => f * TW);
  const COLX = COLS.reduce((a, w, i) => (a.push(i ? a[i - 1] + COLS[i - 1] : M), a), []);
  const HEAD_H = 76, LH = 38, PAD = 20, FIRST_TOP = 600, NEXT_TOP = M, FOOT = 90;

  function wrap(ctx, text, maxW) {
    const out = []; let line = "";
    for (const w of String(text).split(/\s+/)) {
      const t = line ? line + " " + w : w;
      if (ctx.measureText(t).width <= maxW || !line) line = t; else { out.push(line); line = w; }
    }
    if (line) out.push(line);
    return out;
  }

  function render(data, logo) {
    const meas = document.createElement("canvas").getContext("2d");

    // ---- measure table rows
    meas.font = `28px ${F}`;
    const rows = data.rows.length ? data.rows : [{ day: "—", first: true, course: "No classes scheduled", time: "", room: "", teacher: "" }];
    rows.forEach(r => {
      r.cl = wrap(meas, r.course, COLS[1] - 44);
      r.sl = r.sub ? wrap(meas, r.sub, COLS[1] - 44) : [];
      r.h = Math.max(88, (r.cl.length + r.sl.length) * LH + 2 * PAD);
    });

    // ---- measure faculty block (two columns, filled row by row)
    meas.font = `27px ${F}`;
    const fw = (TW - 50) / 2, fRows = [];
    for (let i = 0; i < data.faculty.length; i += 2) {
      const pair = data.faculty.slice(i, i + 2).map(f => ({ ini: f.ini, lines: wrap(meas, `${f.name}${f.title ? ", " + f.title : ""}`, fw - 110) }));
      fRows.push({ pair, h: Math.max(...pair.map(p => p.lines.length)) * 36 + 16 });
    }
    const noteH = data.note ? 50 : 0;
    const facH = data.faculty.length ? 96 + fRows.reduce((s, r) => s + r.h, 0) + noteH : noteH;

    // ---- paginate
    const limit = H - M - FOOT;
    const pages = []; let cur = { rows: [], fac: false }, y = FIRST_TOP + HEAD_H;
    for (const r of rows) {
      if (y + r.h > limit) { pages.push(cur); cur = { rows: [], fac: false }; y = NEXT_TOP + HEAD_H; }
      cur.rows.push(r); y += r.h;
    }
    if (facH) {
      if (y + 50 + facH > limit) { pages.push(cur); cur = { rows: [], fac: false }; y = NEXT_TOP; }
      cur.fac = true;
    }
    pages.push(cur);

    // ---- draw
    return pages.map((pg, pi) => {
      const cv = document.createElement("canvas"); cv.width = W; cv.height = H;
      const g = cv.getContext("2d");
      g.fillStyle = "#fff"; g.fillRect(0, 0, W, H);
      g.textBaseline = "middle";
      let top = NEXT_TOP;

      if (pi === 0) {
        const ly = M, lw = 190, lh = Math.round(lw * logo.naturalHeight / logo.naturalWidth);
        g.drawImage(logo, M, ly, lw, lh);
        const tx = M + lw + 44, tw = TW - lw - 44 - 280;
        g.textAlign = "left"; g.fillStyle = ACCENT; g.font = `bold 40px ${F}`;
        const nm = wrap(g, "Bangladesh Army International University of Science and Technology", tw);
        let ty = ly + 34;
        nm.forEach(l => { g.fillText(l, tx, ty); ty += 50; });
        g.fillStyle = "#555"; g.font = `28px ${F}`; g.fillText("Cumilla, Bangladesh", tx, ty + 6);
        g.fillStyle = "#111"; g.font = `bold 32px ${F}`; g.fillText("Department of Law", tx, ty + 56);

        g.textAlign = "right"; g.fillStyle = "#777"; g.font = `22px ${F}`; g.fillText("Generated by", W - M, ly + 22);
        g.fillStyle = "#111"; g.font = `bold 28px ${F}`; g.fillText("BAIUST Routine", W - M, ly + 60);
        g.fillStyle = "#555"; g.font = `24px ${F}`; g.fillText(data.semester || "", W - M, ly + 98);

        const ry = ly + lh + 36;
        g.fillStyle = ACCENT; g.fillRect(M, ry, TW, 6);
        g.fillStyle = GOLD; g.fillRect(M, ry + 10, TW, 3);

        g.textAlign = "center"; g.fillStyle = "#000"; g.font = `bold 58px ${F}`;
        g.fillText(data.title, W / 2, ry + 110);
        if (data.subtitle) { g.fillStyle = "#555"; g.font = `28px ${F}`; g.fillText(data.subtitle, W / 2, ry + 168); }
        top = FIRST_TOP;
      }

      let yy = top;
      if (pg.rows.length) {
        // header row
        g.fillStyle = ACCENT; g.fillRect(M, yy, TW, HEAD_H);
        g.fillStyle = "#fff"; g.font = `bold 32px ${F}`; g.textAlign = "center";
        ["Day", "Course", "Time Slot", "Room", "Teacher"].forEach((t, i) => g.fillText(t, COLX[i] + COLS[i] / 2, yy + HEAD_H / 2 + 1));
        g.strokeStyle = "#111"; g.lineWidth = 2; g.strokeRect(M, yy, TW, HEAD_H);
        COLX.slice(1).forEach(x => { g.beginPath(); g.moveTo(x, yy); g.lineTo(x, yy + HEAD_H); g.stroke(); });
        yy += HEAD_H;

        // body: group consecutive rows of the same day on this page
        let gi = 0;
        while (gi < pg.rows.length) {
          let gj = gi, gh = 0;
          while (gj < pg.rows.length && (gj === gi || !pg.rows[gj].first)) { gh += pg.rows[gj].h; gj++; }
          // day cell (merged)
          g.strokeStyle = "#111"; g.lineWidth = 2; g.strokeRect(COLX[0], yy, COLS[0], gh);
          g.fillStyle = "#000"; g.font = `28px ${F}`; g.textAlign = "center";
          g.fillText(pg.rows[gi].day, COLX[0] + COLS[0] / 2, yy + gh / 2);
          let ry = yy;
          for (let k = gi; k < gj; k++) {
            const r = pg.rows[k];
            for (let c = 1; c < 5; c++) g.strokeRect(COLX[c], ry, COLS[c], r.h);
            const cy = ry + r.h / 2;
            g.fillStyle = "#000"; g.textAlign = "left"; g.font = `28px ${F}`;
            const n = r.cl.length + r.sl.length; let ty = cy - (n - 1) * LH / 2;
            r.cl.forEach(l => { g.fillText(l, COLX[1] + 22, ty); ty += LH; });
            g.fillStyle = "#555"; g.font = `italic 25px ${F}`;
            r.sl.forEach(l => { g.fillText(l, COLX[1] + 22, ty); ty += LH; });
            g.fillStyle = "#000"; g.font = `28px ${F}`; g.textAlign = "center";
            g.fillText(r.time, COLX[2] + COLS[2] / 2, cy);
            g.fillText(r.room, COLX[3] + COLS[3] / 2, cy);
            g.fillText(r.teacher, COLX[4] + COLS[4] / 2, cy);
            ry += r.h;
          }
          yy += gh; gi = gj;
        }
        yy += 50;
      }

      if (pg.fac) {
        if (data.faculty.length) {
          g.textAlign = "left"; g.fillStyle = ACCENT; g.font = `bold 30px ${F}`;
          g.fillText("FACULTY", M, yy + 14);
          g.fillStyle = GOLD; g.fillRect(M, yy + 42, 120, 5);
          yy += 80;
          fRows.forEach(fr => {
            fr.pair.forEach((p, ci) => {
              const x = M + ci * (fw + 50);
              g.fillStyle = ACCENT; g.font = `bold 27px ${F}`; g.textAlign = "left"; g.fillText(p.ini, x, yy + 14);
              g.fillStyle = "#111"; g.font = `27px ${F}`;
              p.lines.forEach((l, li) => g.fillText((li === 0 ? "— " : "   ") + l, x + 78, yy + 14 + li * 36));
            });
            yy += fr.h;
          });
        }
        if (data.note) { g.fillStyle = "#555"; g.font = `italic 24px ${F}`; g.textAlign = "left"; g.fillText(data.note, M, yy + 30); }
      }

      // footer
      g.fillStyle = "#e3e3e3"; g.fillRect(M, H - M - 40, TW, 2);
      g.fillStyle = "#777"; g.font = `22px ${F}`; g.textAlign = "left";
      g.fillText(`Generated by BAIUST Routine · ${data.generated}`, M, H - M - 8);
      if (pages.length > 1) { g.textAlign = "right"; g.fillText(`Page ${pi + 1} / ${pages.length}`, W - M, H - M - 8); }
      return cv;
    });
  }

  // ---- minimal PDF writer: one JPEG-backed A4 page per canvas
  function toPDF(canvases) {
    const enc = new TextEncoder(), chunks = [], offs = []; let len = 0;
    const put = b => { if (typeof b === "string") b = enc.encode(b); chunks.push(b); len += b.length; };
    const PW = 595.28, PH = 841.89, n = canvases.length;
    const kids = canvases.map((_, i) => `${3 + i * 3} 0 R`).join(" ");
    put("%PDF-1.4\n%\xE2\xE3\xCF\xD3\n");
    offs[1] = len; put("1 0 obj\n<</Type/Catalog/Pages 2 0 R>>\nendobj\n");
    offs[2] = len; put(`2 0 obj\n<</Type/Pages/Kids[${kids}]/Count ${n}>>\nendobj\n`);
    canvases.forEach((cv, i) => {
      const pn = 3 + i * 3, cn = pn + 1, im = pn + 2;
      const b64 = cv.toDataURL("image/jpeg", 0.92).split(",")[1], bin = atob(b64), jpg = new Uint8Array(bin.length);
      for (let k = 0; k < bin.length; k++) jpg[k] = bin.charCodeAt(k);
      const stream = `q ${PW} 0 0 ${PH} 0 0 cm /Im0 Do Q`;
      offs[pn] = len; put(`${pn} 0 obj\n<</Type/Page/Parent 2 0 R/MediaBox[0 0 ${PW} ${PH}]/Resources<</XObject<</Im0 ${im} 0 R>>>>/Contents ${cn} 0 R>>\nendobj\n`);
      offs[cn] = len; put(`${cn} 0 obj\n<</Length ${stream.length}>>\nstream\n${stream}\nendstream\nendobj\n`);
      offs[im] = len; put(`${im} 0 obj\n<</Type/XObject/Subtype/Image/Width ${cv.width}/Height ${cv.height}/ColorSpace/DeviceRGB/BitsPerComponent 8/Filter/DCTDecode/Length ${jpg.length}>>\nstream\n`);
      put(jpg); put("\nendstream\nendobj\n");
    });
    const total = 3 + n * 3, xref = len;
    put(`xref\n0 ${total}\n0000000000 65535 f \n`);
    for (let i = 1; i < total; i++) put(String(offs[i]).padStart(10, "0") + " 00000 n \n");
    put(`trailer\n<</Size ${total}/Root 1 0 R>>\nstartxref\n${xref}\n%%EOF`);
    return new Blob(chunks, { type: "application/pdf" });
  }

  const toPNG = cv => new Promise(res => cv.toBlob(res, "image/png"));
  return { render, toPDF, toPNG };
})();
